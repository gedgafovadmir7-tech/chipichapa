# ---------- примитивы разметки (повторяют XML образца) ----------

def run(text, bold=False, color=None, mono=False, size=None):
    rpr = MONO if mono else TNR
    if bold:
        rpr += '<w:b w:val="1"/><w:bCs w:val="1"/>'
    if color:
        rpr += f'<w:color w:val="{color}"/>'
    if size:
        rpr += f'<w:sz w:val="{size}"/><w:szCs w:val="{size}"/>'
    rpr += '<w:rtl w:val="0"/>'
    return f'<w:r><w:rPr>{rpr}</w:rPr><w:t xml:space="preserve">{escape(text)}</w:t></w:r>'


MARK = re.compile(r"(\*\*.+?\*\*|`[^`]+`)")


def rich(text, mono=False, color=None, size=None, bold=False):
    """**жирный** и `#HEX` (зелёный код, как в образце)."""
    out = []
    for part in MARK.split(text):
        if not part:
            continue
        if part.startswith("**"):
            out.append(run(part[2:-2], bold=True, color=color, size=size))
        elif part.startswith("`"):
            out.append(run(part[1:-1], color=GREEN, mono=mono, size=size, bold=bold))
        else:
            out.append(run(part, color=color, size=size, bold=bold))
    return "".join(out)


def para(runs, style=None, jc=None, before=0, after=0, num=None, ind=None, bold_mark=False, keep_next=False):
    ppr = ""
    if style:
        ppr += f'<w:pStyle w:val="{style}"/>'
    if keep_next:
        ppr += '<w:keepNext/>'
    if num is not None:
        ppr += f'<w:numPr><w:ilvl w:val="0"/><w:numId w:val="{num}"/></w:numPr>'
    if before is not None:
        ppr += f'<w:spacing w:after="{after}" w:before="{before}" w:lineRule="auto"/>'
    if num is not None:
        ppr += '<w:ind w:left="720" w:hanging="360"/>'
    elif ind == 0:
        ppr += '<w:ind w:left="0" w:firstLine="0"/>'
    if jc:
        ppr += f'<w:jc w:val="{jc}"/>'
    bold = '<w:b w:val="1"/><w:bCs w:val="1"/>' if bold_mark else ""
    ppr += f'<w:rPr>{TNR}{bold}</w:rPr>'
    return f'<w:p><w:pPr>{ppr}</w:pPr>{runs}</w:p>'


class Doc:
    def __init__(self):
        self.parts = []
        self.num_next = 300
        self.nums = []        # (numId, abstractId)
        self.images = []      # (rId, file)
        self.bm = 100

    def add(self, xml):
        self.parts.append(xml)

    # заголовки
    def page_break(self):
        self.add(f'<w:p><w:pPr><w:rPr>{TNR}</w:rPr></w:pPr><w:r><w:br w:type="page"/></w:r></w:p>')

    def heading(self, level, text, center=True, page_break=False):
        if page_break:
            self.page_break()
        self.bm += 1
        bm = (f'<w:bookmarkStart w:colFirst="0" w:colLast="0" w:name="_dlkip{self.bm}" w:id="{self.bm}"/>'
              f'<w:bookmarkEnd w:id="{self.bm}"/>')
        p = para(run(text), style=f"Heading{level}", jc="center" if center else None, before=240, after=240,
                 keep_next=True)
        self.add(p.replace("</w:pPr>", "</w:pPr>" + bm, 1))

    def h1(self, text, page_break=True):
        self.heading(1, text, page_break=page_break)

    def h2(self, text):
        self.heading(2, text)

    def h3(self, text):
        self.heading(3, text)

    def h4(self, text):
        self.heading(4, text, center=False)

    # текст
    def p(self, text, mono=False, center=False, keep_next=None):
        if keep_next is None:
            keep_next = text.rstrip().endswith(":")
        self.add(para(rich(text, mono), before=240, after=240, jc="center" if center else None, keep_next=keep_next))

    def line(self, text, mono=False):
        """Строка без отступов: «**Подпись:** текст `#HEX`»."""
        self.add(para(rich(text, mono), keep_next=text.rstrip().endswith(":")))

    def label(self, text, spaced=False):
        self.add(para(run(text, bold=True), before=240 if spaced else 0, after=240 if spaced else 0, bold_mark=True,
                      keep_next=True))

    def note(self, text):
        """Серая подпись 10 pt под цветом, как «Применение: …» в образце."""
        self.add(para(rich(text, color=GRAY, size=20), ind=0))

    def gray(self, text):
        self.add(para(run(text, color=GRAY), before=None))

    def blank(self):
        self.add(para("", before=None))

    def hr(self, after=240):
        self.add(f'<w:p><w:pPr><w:spacing w:after="{after}" w:before="0" w:lineRule="auto"/><w:rPr>{TNR}</w:rPr></w:pPr>'
                 '<w:r><w:pict><v:rect style="width:0.0pt;height:1.5pt" o:hr="t" o:hrstd="t" o:hralign="center" '
                 'fillcolor="#A0A0A0" stroked="f"/></w:pict></w:r></w:p>')

    # списки
    def _new_num(self, abstract):
        self.num_next += 1
        self.nums.append((self.num_next, abstract))
        return self.num_next

    def bullets(self, items, mono=False, spaced=True, abstract=1):
        nid = self._new_num(abstract)
        for i, it in enumerate(items):
            before = 240 if (spaced and i == 0) else 0
            after = 240 if (spaced and i == len(items) - 1) else 0
            self.add(para(rich(it, mono), num=nid, before=before, after=after))

    def numbered(self, items, mono=False):
        self.bullets(items, mono=mono, abstract=41)

    def color(self, name, hexv, rgb, cmyk, use, use_as_note=True, swatch=None):
        sw = swatch or hexv
        mark = "□" if sw.upper() == "#FFFFFF" else "■"
        mark_col = "CCCCCC" if sw.upper() == "#FFFFFF" else sw.lstrip("#").upper()
        self.add(para(run(mark + " ", color=mark_col, size=28) + run(name, bold=True), bold_mark=True, keep_next=True))
        self.bullets([f"HEX: `{hexv}`", f"RGB: {rgb}", f"CMYK: {cmyk}"] + ([] if use_as_note else [f"Применение: {use}"]),
                     spaced=False)
        if use_as_note:
            self.note(f"**Применение**: {use}")

    # картинки
    def image(self, fname, width_in=6.0, caption=None):
        path = os.path.join(IMG_DIR, fname)
        w, h = Image.open(path).size
        cx = int(width_in * 914400)
        cy = int(cx * h / w)
        rid = f"rIdImg{len(self.images) + 1}"
        self.images.append((rid, fname))
        pid = len(self.images) + 10
        drawing = (
            f'<w:r><w:rPr>{TNR}</w:rPr><w:drawing><wp:inline distB="114300" distT="114300" distL="114300" distR="114300">'
            f'<wp:extent cx="{cx}" cy="{cy}"/><wp:effectExtent b="0" l="0" r="0" t="0"/>'
            f'<wp:docPr id="{pid}" name="{fname}"/><a:graphic><a:graphicData uri="http://schemas.openxmlformats.org/drawingml/2006/picture">'
            f'<pic:pic><pic:nvPicPr><pic:cNvPr id="0" name="{fname}"/><pic:cNvPicPr preferRelativeResize="0"/></pic:nvPicPr>'
            f'<pic:blipFill><a:blip r:embed="{rid}"/><a:srcRect b="0" l="0" r="0" t="0"/><a:stretch><a:fillRect/></a:stretch></pic:blipFill>'
            f'<pic:spPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="{cx}" cy="{cy}"/></a:xfrm><a:prstGeom prst="rect"/><a:ln/></pic:spPr>'
            f'</pic:pic></a:graphicData></a:graphic></wp:inline></w:drawing></w:r>')
        self.add(para(drawing, jc="center", before=240, after=120 if caption else 240))
        if caption:
            self.add(para(run(caption, color=GRAY, size=20), jc="center", before=0, after=240))


